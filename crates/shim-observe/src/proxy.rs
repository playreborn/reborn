/// Callback number of `UserStatsReceived_t` (`docs/shim/meanings.md`,
/// experiment 21).
const STATS_RECEIVED: u32 = 0x44d;

/// How long the worker waits for `rebornd`'s `StatsReceived` after
/// `RequestStats` was accepted. The official 0x44d came 250 to 310 ms
/// after the game's request (experiments 20, 21); `rebornd`'s own fetch
/// backs off for up to 15 s over its five tries (ADR 0055, "Rate limits").
/// A longer wait is logged as no Reborn answer; meanwhile other
/// comparisons queue up (at most [`MAX_ASKS`]).
const STATS_WAIT: std::time::Duration = std::time::Duration::from_secs(30);

/// Comparisons that may wait at once; more are logged as skipped.
const MAX_ASKS: usize = 16;

/// The worker thread that asks `rebornd`, started on first use; `None` if
/// it could not be started.
static ASKS: OnceLock<Option<std::sync::mpsc::SyncSender<Ask>>> = OnceLock::new();

/// Hands a comparison with `rebornd`'s answer to the worker thread
/// (ADR 0055, 0056); never waits.
fn ask(prefix: String, official: Official) {
    let sender = ASKS.get_or_init(|| {
        let (sender, asks) = std::sync::mpsc::sync_channel(MAX_ASKS);
        std::thread::Builder::new()
            .name("reborn-shadow".to_owned())
            .spawn(move || answer_asks(asks))
            .ok()
            .map(|_| sender)
    });
    let ask = Ask { prefix, official };
    match sender {
        Some(sender) => {
            if let Err(error) = sender.try_send(ask) {
                let (ask, why) = match error {
                    std::sync::mpsc::TrySendError::Full(ask) => (ask, "worker busy"),
                    std::sync::mpsc::TrySendError::Disconnected(ask) => (ask, "worker thread gone"),
                };
                skipped(ask, why);
            }
        }
        None => skipped(ask, "no worker thread"),
    }
}

/// An ask the worker never got: its log line says so. For the
/// achievement wake, everything waiting in [`ACHIEVEMENTS`] is dropped and
/// logged, so the next achievement call wakes the worker again.
fn skipped(ask: Ask, why: &str) {
    let note = if why == "no worker thread" {
        "shadow: no worker thread".to_owned()
    } else {
        format!("shadow: skipped, {why}")
    };
    if matches!(ask.official, Official::Achievements) {
        // Taken (which also clears the open wake) before logging, so the
        // lock is not held while the log is written.
        let waiting = achievements().take();
        let last = waiting.last().map(|(prefix, _)| prefix.clone());
        for (prefix, _) in waiting {
            log(&format!("{prefix} {note}"));
        }
        survey_skipped(last.as_deref(), why);
    } else {
        log(&format!("{} {note}", ask.prefix));
    }
}

/// What the official client answered at the achievement calls, waiting
/// for Reborn's list (ADR 0059, decision 2). Bounded by
/// [`crate::daemon::MAX_WAITING_ACHIEVEMENTS`]; holds digests, never names.
static ACHIEVEMENTS: Mutex<crate::daemon::AchievementQueue> =
    Mutex::new(crate::daemon::AchievementQueue::new());

/// The achievement queue, also after a panic elsewhere held the lock (it
/// holds plain data, which stays consistent).
fn achievements() -> std::sync::MutexGuard<'static, crate::daemon::AchievementQueue> {
    ACHIEVEMENTS
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
}

/// Keeps one official achievement answer for the comparison and wakes the
/// worker if no wake is open (ADR 0059, decision 2). Never waits for
/// `rebornd`; the lock is held only to push.
fn achievement_shadow(prefix: String, official: crate::daemon::OfficialAchievement) {
    use crate::daemon::Pushed;
    let pushed = achievements().push(prefix, official);
    match pushed {
        Pushed::Wake => ask(String::new(), Official::Achievements),
        Pushed::Kept => {}
        Pushed::Full(prefix) => {
            let why = format!(
                "{} achievement answers already wait",
                crate::daemon::MAX_WAITING_ACHIEVEMENTS
            );
            log(&format!("{prefix} shadow: skipped, {why}"));
            survey_skipped(Some(&prefix), &why);
        }
    }
}

/// The survey of ADR 0061 for this process, fed by the worker and ended
/// early by a skipped official answer; holds digests, never names.
static SURVEY: Mutex<crate::daemon::AchievementSurvey> =
    Mutex::new(crate::daemon::AchievementSurvey::new());

/// The survey, also after a panic elsewhere held the lock (plain data).
fn survey() -> std::sync::MutexGuard<'static, crate::daemon::AchievementSurvey> {
    SURVEY
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
}

/// An official achievement answer was not kept, so the official list can
/// never be complete: the survey's "not surveyed" note, once, with the
/// prefix of the skipped call (if there is one). The lock is released
/// before logging.
fn survey_skipped(prefix: Option<&str>, why: &str) {
    let note = survey().give_up(&format!("an official answer was skipped ({why})"));
    if let Some(note) = note {
        match prefix {
            Some(prefix) => log(&format!("{prefix} {note}")),
            None => log(&note),
        }
    }
}

/// The official text of a `GetAchievementName` call: the SHA-256 of the
/// NUL-terminated bytes at `address` (at most [`MAX_NAME_BYTES`], in one
/// readable region, read in place) and of their normalised form (ADR
/// 0061). The copy of the bytes is zeroed when dropped.
fn achievement_digest_at(address: u64) -> Result<crate::daemon::NameDigests, &'static str> {
    let text = c_text_at(address, MAX_NAME_BYTES).ok_or("no text at the result")?;
    Ok(crate::daemon::NameDigests::of(text.bytes()))
}

/// The worker: one shadow session with `rebornd` for this process, for the
/// app given to `arm` only; one `AppOwnership` per `BIsSubscribed`, one
/// `RequestStats` per 0x44d, one `ComparePersonaName` per
/// `SteamFriends017` position 0, one `CloudFileSize` or `CloudRead` per
/// cloud read, all on the same link and queue. For the achievement calls
/// one `RequestStats` until its `StatsReceived` came (ADR 0059; `rebornd`
/// answers every `RequestStats` of a run from one fetch), then every
/// official answer waiting in [`ACHIEVEMENTS`] is compared.
fn answer_asks(asks: std::sync::mpsc::Receiver<Ask>) {
    use crate::daemon::{
        compare_achievement, compare_file_read, compare_file_size, compare_persona_name,
        compare_stats_received, compare_subscribed, connect_with_waits,
    };
    let mut link = crate::daemon::ShadowLink::default();
    let pid = std::process::id();
    for ask in asks {
        if matches!(ask.official, Official::Achievements) {
            // Waits for Reborn's list first; answers that come meanwhile
            // join the queue and are compared below too.
            let reborn = given_app_id()
                .ok_or(())
                .map(|app_id| link.achievements(pid, app_id, connect_with_waits, STATS_WAIT));
            // Bound first: the guard is dropped here, not held while
            // the log is written.
            let waiting = achievements().take();
            for (prefix, official) in waiting {
                let note = match &reborn {
                    Err(()) => "shadow: no app ID given".to_owned(),
                    Ok(reborn) => compare_achievement(&official, reborn.clone()),
                };
                log(&format!("{prefix} {note}"));
                // ADR 0061: once the official list is complete, the set
                // counts and the index mapping (or why there are none),
                // after the call that completed it. Bound first, so the
                // lock is not held while the log is written.
                let notes = {
                    let mut guard = survey();
                    guard.add(&official);
                    guard.finish(match &reborn {
                        Err(()) => Err("no app ID given".to_owned()),
                        Ok(reborn) => reborn.clone(),
                    })
                };
                for note in notes.into_iter().flatten() {
                    log(&format!("{prefix} {note}"));
                }
            }
            continue;
        }
        let note = match (given_app_id(), ask.official) {
            (None, _) => "shadow: no app ID given".to_owned(),
            (Some(app_id), Official::Subscribed(rax)) => {
                compare_subscribed(rax, link.subscribed(pid, app_id, connect_with_waits))
            }
            (Some(app_id), Official::StatsReceived(official)) => compare_stats_received(
                official,
                app_id,
                link.stats_result(pid, app_id, connect_with_waits, STATS_WAIT),
            ),
            (Some(app_id), Official::PersonaName(digest)) => match digest {
                Ok(digest) => compare_persona_name(Ok(()), || {
                    link.persona_name(pid, app_id, digest, connect_with_waits)
                }),
                Err(why) => compare_persona_name(Err(why), || Err("not asked".to_owned())),
            },
            (Some(app_id), Official::FileSize { name, rax }) => {
                compare_file_size(rax, link.file_size(pid, app_id, connect_with_waits, &name))
            }
            (Some(app_id), Official::FileRead { name, max, read }) => compare_file_read(
                read,
                link.file_read(pid, app_id, connect_with_waits, &name, max),
            ),
            (Some(_), Official::Achievements) => continue,
        };
        log(&format!("{} {note}", ask.prefix));
    }
}

/// The comparison for a cloud read that returned `rax` (ADR 0055, stage
/// 1), or why there is none. For `FileRead` the official client's bytes
/// are hashed here, on the game's thread right after the return; only
/// their count and SHA-1 are kept.
fn cloud_official(shadow: Shadow, rax: u64, args: &CloudArgs) -> Result<Official, &'static str> {
    let name = args.name.clone().ok_or("file name not readable")?;
    match shadow {
        Shadow::FileSize => Ok(Official::FileSize { name, rax }),
        Shadow::FileRead => Ok(Official::FileRead {
            name,
            max: args.size,
            read: official_read(rax, args)?,
        }),
        _ => Err("not a cloud read"),
    }
}

/// What the official `FileRead` wrote into the game's buffer: its result
/// (the low 32 bits of `rax`, a byte count, `docs/shim/meanings.md`
/// experiment 1) and the SHA-1 of that many bytes at the buffer address.
/// Refused when the count is negative, larger than the buffer size the
/// game passed or than [`MAX_SHADOW_READ`], or the range is not readable.
/// The bytes are copied [`HASH_CHUNK`] at a time into the hash, never all
/// at once. This runs on the game's thread before `FileRead` returns to
/// the game: SHA-1 in software hashes several hundred MB a second, so the
/// recorded 44875-byte save costs well under a millisecond, and the
/// 16 MiB bound some tens of milliseconds at worst (once, at load).
fn official_read(rax: u64, args: &CloudArgs) -> Result<crate::daemon::OfficialRead, &'static str> {
    use sha1::{Digest, Sha1};
    let count = rax as u32 as i32;
    let len = usize::try_from(count).map_err(|_| "official result negative")?;
    if len > args.size as usize {
        return Err("official result larger than the buffer");
    }
    if len > MAX_SHADOW_READ {
        return Err("official result larger than 16 MiB");
    }
    if len > 0 && !range_readable(args.buffer, len) {
        return Err("buffer not readable");
    }
    let mut hasher = Sha1::new();
    let mut chunk = vec![0u8; len.min(HASH_CHUNK)];
    let mut done = 0;
    while done < len {
        let take = (len - done).min(HASH_CHUNK);
        let start = (args.buffer as usize) + done;
        // SAFETY: `range_readable` checked just now that the whole range
        // `buffer..buffer + len` lies in committed, readable regions; this
        // piece is inside it and `chunk` has room for `take` bytes. No
        // reference to the game's memory is made. As in `bytes_in`, the
        // memory is assumed not to be freed during the copy (the game's
        // call has returned and the game is still in our return stub).
        unsafe {
            std::ptr::copy_nonoverlapping(start as *const u8, chunk.as_mut_ptr(), take);
        }
        hasher.update(&chunk[..take]);
        done += take;
    }
    Ok(crate::daemon::OfficialRead {
        len,
        sha1: hasher.finalize().into(),
    })
}

/// Whether the `len` bytes at `address` all lie in committed, readable
/// memory, region after region (`VirtualQuery`, as in [`readable_end`]).
fn range_readable(address: u64, len: usize) -> bool {
    if address < 0x1_0000 {
        return false;
    }
    let Ok(start) = usize::try_from(address) else {
        return false;
    };
    let Some(end) = start.checked_add(len) else {
        return false;
    };
    let mut at = start;
    while at < end {
        match readable_end(at) {
            Some(region_end) if region_end > at => at = region_end,
            _ => return false,
        }
    }
    true
}

/// The cloud file name at `address`: 1 to [`MAX_NAME`] bytes of UTF-8
/// followed by a NUL, all within one readable memory region (checked with
/// `VirtualQuery`, as in [`ascii_at`]).
fn name_at(address: u64) -> Option<String> {
    if address < 0x1_0000 {
        return None;
    }
    let start = usize::try_from(address).ok()?;
    let end = readable_end(start)?;
    let mut name = Vec::new();
    for offset in 0..=MAX_NAME {
        let at = start.checked_add(offset)?;
        if at >= end {
            return None;
        }
        // SAFETY: `at` lies inside a committed, readable region that
        // `readable_end` just checked.
        let byte = unsafe { std::ptr::read_volatile(at as *const u8) };
        if byte == 0 {
            return (!name.is_empty())
                .then(|| String::from_utf8(name).ok())
                .flatten();
        }
        name.push(byte);
    }
    None
}

/// The compared fields of callback 0x44d, if the callback `Steam_BGetCallback`
/// wrote at `rdx` is one (`rax` 1): its header (step 4d, ADR 0050) names
/// 0x44d and a readable payload of 1 to [`MAX_PAYLOAD`] bytes. Only the
/// first [`crate::daemon::STATS_READ`] payload bytes are read: the
/// comparison does not read bytes 12..20 (the Steam ID). The step-4b line
/// still logs the 0x44d payload locally (ADR 0050, 0054).
fn stats_received_at(rax: u64, rdx: u64) -> Option<crate::daemon::OfficialStats> {
    if rax & 0xff != 1 {
        return None;
    }
    let header = bytes_in(rdx, CALLBACK_HEADER)?;
    let word = |at: usize| {
        u32::from_le_bytes([header[at], header[at + 1], header[at + 2], header[at + 3]])
    };
    if word(4) != STATS_RECEIVED {
        return None;
    }
    let address = u64::from(word(8)) | (u64::from(word(12)) << 32);
    let size = word(16) as usize;
    if size == 0 || size > MAX_PAYLOAD {
        return None;
    }
    let first = bytes_in(address, size.min(crate::daemon::STATS_READ))?;
    crate::daemon::OfficialStats::new(size, &first)
}

/// Longest result text hashed for the persona name and achievement name
/// comparisons; a longer one counts as no text. A bound chosen here, not a
/// documented limit.
const MAX_NAME_BYTES: usize = 1024;

/// The SHA-256 of the NUL-terminated text at `address`, read in place and
/// dropped (ADR 0056), or why there is none: not readable, no NUL within
/// [`MAX_NAME_BYTES`] in one memory region. Any bytes count, so a name in
/// UTF-8 is hashed as it is.
fn text_digest_at(address: u64) -> Result<reborn_shim_protocol::NameDigest, &'static str> {
    let no_text = "no text at the result";
    let text = c_text_at(address, MAX_NAME_BYTES).ok_or(no_text)?;
    reborn_shim_protocol::NameDigest::from_hex(&sha256_hex(text.bytes())).ok_or(no_text)
}

/// A copy of text that may be account data: zeroed when dropped (best
/// effort; the buffer is allocated once, so no other copy is left behind
/// by growing it).
struct Wiped(Vec<u8>);

impl Wiped {
    fn bytes(&self) -> &[u8] {
        &self.0
    }
}

impl Drop for Wiped {
    fn drop(&mut self) {
        self.0.fill(0);
        // Keeps the zeroing from being optimised away as a dead store.
        std::hint::black_box(&self.0);
    }
}

/// The bytes of the NUL-terminated text at `address` (without the NUL),
/// if it is readable, ends within `max` bytes and lies in one memory
/// region. Never logged by any caller; zeroed when dropped.
fn c_text_at(address: u64, max: usize) -> Option<Wiped> {
    // As in `ascii_at`: the lowest 64 KiB are never mapped.
    if address < 0x1_0000 {
        return None;
    }
    let start = usize::try_from(address).ok()?;
    let end = readable_end(start)?;
    // Room for `max` bytes up front: pushing never reallocates, so every
    // byte read stays in this one buffer, which `Wiped` zeroes.
    let mut text = Wiped(Vec::with_capacity(max));
    for offset in 0..=max {
        let at = start.checked_add(offset)?;
        if at >= end {
            return None;
        }
        // SAFETY: `at` lies inside a committed, readable region that
        // `readable_end` just checked.
        let byte = unsafe { std::ptr::read_volatile(at as *const u8) };
        if byte == 0 {
            return Some(text);
        }
        if offset == max {
            return None;
        }
        text.0.push(byte);
    }
    None
}

/// Whether the call's argument texts stay out of the log: for the persona
/// name comparison a leftover register could point to the name (ADR 0056);
/// for the account-data shadows (ownership, cloud reads, ADR 0055) the file
/// name and old buffer contents; for the achievement comparisons (ADR
/// 0059) a leftover register could point to an achievement name.
fn hides_texts(interface: &str, slot: usize) -> bool {
    shadow_for(interface, slot).is_some_and(|shadow| {
        shadow == Shadow::PersonaName || shadow.is_account_data() || shadow.is_achievement()
    })
}

/// The result part of a return line: `rax` as a number, except for an
/// ownership or cloud read shadow (account data, [`Shadow::is_account_data`]). For the persona name comparison `rax`
/// is an address, never the text it points to.
fn result_note(rax: u64, shadow: Option<Shadow>) -> String {
    if shadow.is_some_and(Shadow::is_account_data) {
        "rax hidden (account data)".to_owned()
    } else {
        format!("rax=0x{rax:x}")
    }
}

