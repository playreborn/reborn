/// Addresses of the real functions, in [`ENTRY_POINTS`] order.
static TARGETS: OnceLock<[usize; 5]> = OnceLock::new();
/// Start and end of the real `steamclient64.dll` in memory.
static MODULE: OnceLock<(usize, usize)> = OnceLock::new();
/// The log file, `None` if it cannot be opened (or in tests).
static LOG: OnceLock<Option<Mutex<File>>> = OnceLock::new();
static CALLS: [AtomicU64; 5] = [const { AtomicU64::new(0) }; 5];
static START: OnceLock<Instant> = OnceLock::new();
/// Whether stand-ins are turned off (`read-only` marker).
static READ_ONLY: OnceLock<bool> = OnceLock::new();
/// The stand-in objects handed out so far, by stub table.
static OBJECTS: [OnceLock<Object>; STAND_INS] = [const { OnceLock::new() }; STAND_INS];
/// Held while a stand-in is being created.
static CREATING: Mutex<()> = Mutex::new(());
static METHOD_CALLS: [AtomicU64; STAND_INS * SLOTS] =
    [const { AtomicU64::new(0) }; STAND_INS * SLOTS];

/// A stand-in object: only its first field, pointing to a stub table.
#[repr(C)]
struct StandIn {
    table: usize,
}

/// What a stand-in stands for.
#[derive(Debug)]
struct Object {
    stand_in: usize,
    real: usize,
    /// The real object's table (its first field).
    real_table: usize,
    /// Entries counted in step 3a.
    counted: usize,
    /// The text `CreateInterface` was asked with.
    name: Box<str>,
}

/// What kind of stub a call came through.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Kind {
    /// One of the five exported entry points, by position.
    Export(usize),
    /// A position in a stand-in object's table.
    Method { object: usize, slot: usize },
}

/// The argument registers as a stub saved them (offsets 0x20 to 0x80 of
/// its stack frame).
#[repr(C)]
struct Saved {
    xmm: [[u64; 2]; 4],
    rcx: u64,
    rdx: u64,
    r8: u64,
    r9: u64,
}

/// A call that has not returned yet.
#[derive(Clone, Debug, PartialEq, Eq)]
struct Pending {
    /// Stack pointer at the stub's entry (where the return address is).
    entry_rsp: usize,
    return_address: usize,
    kind: Kind,
    call: u64,
    logged: bool,
    /// For `CreateInterface`: the text it was asked with.
    interface: Option<Box<str>>,
    /// For `Steam_BGetCallback`: `rdx` and `r8` when the call started
    /// (step 4b).
    outputs: Option<[u64; 2]>,
    /// For a listed call that is logged: what to read when it returns
    /// (step 4c).
    after: Option<After>,
    /// For a call in [`SHADOWS`] that is logged: Reborn's answer to compare
    /// when it returns (ADR 0046).
    shadow: Option<Shadow>,
}

/// A read to do when a listed call returns (step 4c, ADR 0043).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum After {
    ResultText,
    /// The register's name and the address it held when the call started.
    Bytes {
        register: &'static str,
        address: u64,
    },
}

thread_local! {
    static PENDING: RefCell<Vec<Pending>> = const { RefCell::new(Vec::new()) };
}

macro_rules! stub {
    ($name:literal, $index:literal) => {
        core::arch::global_asm!(
            ".text",
            concat!(".globl ", $name),
            ".p2align 4",
            concat!(".seh_proc ", $name),
            concat!($name, ":"),
            // Entry: rsp is 8 mod 16 and points to the return address.
            // 0x88 more makes it 16-aligned for the call, with 32 bytes of
            // shadow space at the bottom.
            "sub rsp, 0x88",
            ".seh_stackalloc 0x88",
            ".seh_endprologue",
            "mov [rsp + 0x60], rcx",
            "mov [rsp + 0x68], rdx",
            "mov [rsp + 0x70], r8",
            "mov [rsp + 0x78], r9",
            "movdqu [rsp + 0x20], xmm0",
            "movdqu [rsp + 0x30], xmm1",
            "movdqu [rsp + 0x40], xmm2",
            "movdqu [rsp + 0x50], xmm3",
            concat!("mov ecx, ", $index),
            "lea rdx, [rsp + 0x20]",
            "mov r8, [rsp + 0x88]",
            "lea r9, [rsp + 0x88]",
            "call {observe}",
            // The real function returns into the return stub.
            "lea r10, [rip + reborn_observe_return_stub]",
            "mov [rsp + 0x88], r10",
            "movdqu xmm0, [rsp + 0x20]",
            "movdqu xmm1, [rsp + 0x30]",
            "movdqu xmm2, [rsp + 0x40]",
            "movdqu xmm3, [rsp + 0x50]",
            "mov rcx, [rsp + 0x60]",
            "mov rdx, [rsp + 0x68]",
            "mov r8, [rsp + 0x70]",
            "mov r9, [rsp + 0x78]",
            "add rsp, 0x88",
            // rax holds the real function; it is not an argument register.
            "jmp rax",
            ".seh_endproc",
            observe = sym observe_call,
        );
    };
}

