/// Called by the stubs: logs the call, remembers where it returns to and
/// gives the real function's address. Never unwinds into the stubs; a
/// panic ends the process.
extern "C" fn observe_call(
    index: u32,
    saved: *mut Saved,
    return_address: usize,
    entry_rsp: usize,
) -> usize {
    let result = std::panic::catch_unwind(|| {
        let index = index as usize;
        // SAFETY: the stub passes a pointer to its saved registers, which
        // stay in place until this function returns; it restores the
        // registers from there afterwards.
        let saved = unsafe { &mut *saved };
        let swapped = swap_stand_ins(saved, true);
        let call = CALLS[index].fetch_add(1, Ordering::Relaxed) + 1;
        let logged = should_log(call);
        if logged {
            log(&format!(
                "{} ms {:?} {} call {call}{swapped} {}",
                elapsed_ms(),
                std::thread::current().id(),
                ENTRY_POINTS[index],
                describe_registers(saved, true)
            ));
        }
        let interface = (index == CREATE_INTERFACE)
            .then(|| ascii_at(saved.rcx))
            .flatten()
            .map(String::into_boxed_str);
        let outputs = (index == B_GET_CALLBACK).then_some([saved.rdx, saved.r8]);
        PENDING.with(|pending| {
            pending.borrow_mut().push(Pending {
                entry_rsp,
                return_address,
                kind: Kind::Export(index),
                call,
                logged,
                interface,
                outputs,
                after: None,
                shadow: None,
                cloud: None,
                index: None,
            });
        });
        targets()[index]
    });
    result.unwrap_or_else(|_| std::process::abort())
}

/// Called by the return stub: logs the result and gives the game's
/// return address. `after_rsp` is the stack pointer after the real
/// function returned; `rax_slot` is where the return stub keeps `rax`, so a
/// stand-in can replace the result of `CreateInterface` (step 3b).
extern "C" fn observe_return(rax: u64, xmm0: u64, after_rsp: usize, rax_slot: *mut u64) -> usize {
    let result = std::panic::catch_unwind(|| {
        let found = PENDING.with(|pending| take_pending(&mut pending.borrow_mut(), after_rsp - 8));
        let Some(call) = found else {
            log("return without a matching call; stopping");
            std::process::abort();
        };
        let name = kind_name(call.kind);
        let thread = std::thread::current().id();
        if call.logged {
            // For an ownership shadow the result is account data: together
            // with the shadow line it would give Reborn's answer, so it is
            // not logged (ADR 0055: only match or mismatch).
            let result = result_note(rax, call.shadow);
            log(&format!(
                "{} ms {thread:?} {name} return {} {result} xmm0=0x{xmm0:x}",
                elapsed_ms(),
                call.call
            ));
        }
        // Step 4b: what the client wrote for the game, logged for every
        // such call (they are rare), not only the first ones.
        if let Some(outputs) = call.outputs
            && let Some(note) = describe_callback(rax, outputs)
        {
            log(&format!(
                "{} ms {thread:?} {name} return {} {note}",
                elapsed_ms(),
                call.call
            ));
            // ADR 0055, stage 1: compare a stats callback with what
            // `rebornd` would report, off the game's thread; the game keeps
            // the official callback unchanged.
            if let Some(official) = stats_received_at(rax, outputs[0]) {
                let prefix = format!(
                    "{} ms {thread:?} {name} return {} callback 0x44d",
                    elapsed_ms(),
                    call.call
                );
                ask(prefix, Official::StatsReceived(official));
            }
        }
        // Step 4c: listed calls, only when they are logged.
        if let Some(after) = call.after {
            log(&format!(
                "{} ms {thread:?} {name} return {} {}",
                elapsed_ms(),
                call.call,
                describe_after(rax, after)
            ));
        }
        // ADR 0046: compare with Reborn's own answer; the game keeps the
        // official client's result.
        if let Some(shadow) = call.shadow {
            let prefix = format!("{} ms {thread:?} {name} return {}", elapsed_ms(), call.call);
            match shadow {
                // ADR 0055: Reborn's answer comes from `rebornd`, asked
                // off the game's thread.
                Shadow::Subscribed => ask(prefix, Official::Subscribed(rax)),
                // ADR 0056: the text is read and hashed here, before the
                // game can change it; only the digest leaves this thread.
                Shadow::PersonaName => {
                    ask(prefix, Official::PersonaName(text_digest_at(rax)));
                }
                // ADR 0055, stage 1: the cloud reads, from `rebornd`'s
                // shadow folder.
                Shadow::FileSize | Shadow::FileRead => {
                    let args = call.cloud.as_ref().ok_or("no arguments");
                    match args.and_then(|args| cloud_official(shadow, rax, args)) {
                        Ok(official) => ask(prefix, official),
                        Err(why) => log(&format!("{prefix} shadow: skipped, {why}")),
                    }
                }
                // ADR 0059: kept until Reborn's list is there; the name is
                // hashed here, before the game can change it.
                Shadow::AchievementCount => achievement_shadow(
                    prefix,
                    crate::daemon::OfficialAchievement::Count(rax as u32),
                ),
                Shadow::AchievementName => match call.index {
                    Some(index) => achievement_shadow(
                        prefix,
                        crate::daemon::OfficialAchievement::Name {
                            index,
                            text: achievement_digest_at(rax),
                        },
                    ),
                    None => {
                        log(&format!("{prefix} shadow: skipped, no index"));
                        survey_skipped(Some(&prefix), "no index");
                    }
                },
                _ => log(&format!(
                    "{prefix} {}",
                    describe_shadow(rax, shadow, given_app_id())
                )),
            }
        }
        // CreateInterface (step 3b), and calls through stand-ins that passed
        // a text (step 3c, ADR 0041).
        let wants_stand_in = match call.kind {
            Kind::Export(index) => index == CREATE_INTERFACE,
            Kind::Method { .. } => call.interface.is_some(),
        };
        if wants_stand_in && let Some(&module) = MODULE.get() {
            // Step 3a of ADR 0040: what does the result look like?
            let shape = shape_of(rax, module);
            if call.logged {
                log(&format!(
                    "{} ms {thread:?} {name} result {} {}",
                    elapsed_ms(),
                    call.call,
                    describe_shape(&shape, module)
                ));
            }
            // Hand out a stand-in instead.
            let interface = call.interface.as_deref().unwrap_or("?");
            if let Some((stand_in, object)) = stand_in_for(rax, &shape, interface) {
                // SAFETY: the return stub passes the stack slot where it
                // keeps rax; it reads it back after this function returns.
                unsafe { *rax_slot = stand_in as u64 };
                log(&format!(
                    "{} ms {thread:?} {name} result {} replaced by stand-in {object} (0x{stand_in:x}) for {interface}",
                    elapsed_ms(),
                    call.call
                ));
            }
        }
        call.return_address
    });
    result.unwrap_or_else(|_| std::process::abort())
}

/// Called by the stand-in stubs (step 3b): `number` is
/// `object * SLOTS + position`. Puts the real object into `rcx` if `rcx`
/// holds the stand-in, logs the call, remembers where it returns to and
/// gives the real table's entry at the same position.
extern "C" fn observe_method(
    number: u32,
    saved: *mut Saved,
    return_address: usize,
    entry_rsp: usize,
) -> usize {
    let result = std::panic::catch_unwind(|| {
        let number = number as usize;
        let (object, slot) = (number / SLOTS, number % SLOTS);
        let Some(info) = OBJECTS.get(object).and_then(OnceLock::get) else {
            log(&format!(
                "call through stand-in {object}, which does not exist; stopping"
            ));
            std::process::abort();
        };
        // SAFETY: the stub passes a pointer to its saved registers, which
        // stay in place until this function returns; it restores rcx from
        // there afterwards.
        let saved = unsafe { &mut *saved };
        let this = if saved.rcx as usize == info.stand_in {
            saved.rcx = info.real as u64;
            "rcx held the stand-in, now the real object"
        } else {
            "rcx did not hold the stand-in, left as it was"
        };
        // A shadowed account-data call (ADR 0055): no register text and no
        // `r9` in the log, and no text kept as a stand-in name.
        let hidden = shadow_for(&info.name, slot).is_some_and(Shadow::is_account_data);
        // Texts are looked for before swapping, in the registers the
        // object is not in (step 3c); never for the persona name call.
        let hide_texts = hides_texts(&info.name, slot);
        let interface = if hide_texts {
            None
        } else {
            [saved.rdx, saved.r8, saved.r9]
                .into_iter()
                .find_map(ascii_at)
                .map(String::into_boxed_str)
        };
        let call = METHOD_CALLS[number].fetch_add(1, Ordering::Relaxed) + 1;
        let logged = should_log(call);
        // Step 4c: the registers as the call started, before any swap.
        let after = logged
            .then(|| after_for(&info.name, slot, saved, entry_rsp))
            .flatten();
        let shadow = logged.then(|| shadow_for(&info.name, slot)).flatten();
        // ADR 0055, stage 1: a cloud read's arguments, copied before the
        // official client runs.
        let cloud = shadow
            .filter(|shadow| shadow.takes_file_name())
            .map(|_| CloudArgs {
                name: name_at(saved.rdx),
                buffer: saved.r8,
                size: saved.r9 as u32,
            });
        // ADR 0059: `GetAchievementName`'s `uint32` index, before any swap.
        let index = (shadow == Some(Shadow::AchievementName)).then_some(saved.rdx as u32);
        let swapped = swap_stand_ins(saved, false);
        if logged {
            let beyond = if slot >= info.counted {
                " (beyond the counted entries)"
            } else {
                ""
            };
            log(&format!(
                "{} ms {:?} {} call {call} ({this}{beyond}){swapped} {}",
                elapsed_ms(),
                std::thread::current().id(),
                kind_name(Kind::Method { object, slot }),
                if hidden {
                    describe_registers_hidden(saved)
                } else {
                    describe_registers(saved, !hide_texts)
                }
            ));
        }
        let Some(target) = info
            .real_table
            .checked_add(slot * 8)
            .and_then(read_u64)
            .and_then(|value| usize::try_from(value).ok())
        else {
            log(&format!(
                "cannot read position {slot} of the real table; stopping"
            ));
            std::process::abort();
        };
        // Answer mode (ADR 0046): Reborn's function instead of the official
        // client's, never with `--read-only`.
        let read_only = *READ_ONLY
            .get_or_init(|| own_dir().is_some_and(|dir| dir.join(READ_ONLY_MARKER).exists()));
        let answered = (!read_only).then(|| answer_for(&info.name, slot)).flatten();
        let target = answered.unwrap_or(target);
        let (shadow, cloud, index) = if answered.is_some() {
            (None, None, None)
        } else {
            (shadow, cloud, index)
        };
        if answered.is_some() && logged {
            log(&format!(
                "{} ms {:?} {} call {call} answered by Reborn, not forwarded",
                elapsed_ms(),
                std::thread::current().id(),
                kind_name(Kind::Method { object, slot }),
            ));
        }
        PENDING.with(|pending| {
            pending.borrow_mut().push(Pending {
                entry_rsp,
                return_address,
                kind: Kind::Method { object, slot },
                call,
                logged,
                interface,
                outputs: None,
                after,
                shadow,
                cloud,
                index,
            });
        });
        target
    });
    result.unwrap_or_else(|_| std::process::abort())
}

/// A name for log lines: the entry point, or `SteamClient020#5` for
/// position 5 of the stand-in for `SteamClient020`.
fn kind_name(kind: Kind) -> String {
    match kind {
        Kind::Export(index) => ENTRY_POINTS[index].to_owned(),
        Kind::Method { object, slot } => {
            let name = OBJECTS
                .get(object)
                .and_then(OnceLock::get)
                .map_or("?", |info| &info.name);
            format!("{name}#{slot}")
        }
    }
}

/// Puts the real object into every argument register that holds a
/// stand-in's address (`rcx` only with `include_rcx`; for calls through a
/// stand-in, `observe_method` handles `rcx` itself). Returns a note for
/// the log line, empty if nothing was swapped (step 3c, ADR 0041).
fn swap_stand_ins(saved: &mut Saved, include_rcx: bool) -> String {
    let mut note = String::new();
    let registers: [(&str, &mut u64); 4] = [
        ("rcx", &mut saved.rcx),
        ("rdx", &mut saved.rdx),
        ("r8", &mut saved.r8),
        ("r9", &mut saved.r9),
    ];
    for (name, value) in registers {
        if name == "rcx" && !include_rcx {
            continue;
        }
        if let Some(info) = OBJECTS
            .iter()
            .filter_map(OnceLock::get)
            .find(|info| info.stand_in as u64 == *value)
        {
            *value = info.real as u64;
            let _ = write!(
                note,
                " ({name} held the stand-in for {}, now the real object)",
                info.name
            );
        }
    }
    note
}

/// The stand-in for `real`, created on first use: only if stand-ins are on,
/// `real` has the shape of step 3a with at most [`MAX_STAND_IN_ENTRIES`]
/// counted entries, and a stub table is free. The same real object always
/// gets the same stand-in. Returns its address and number.
fn stand_in_for(real: u64, shape: &Shape, interface: &str) -> Option<(usize, usize)> {
    if *READ_ONLY.get_or_init(|| own_dir().is_some_and(|dir| dir.join(READ_ONLY_MARKER).exists())) {
        return None;
    }
    let &Shape::Table { first, entries } = shape else {
        return None;
    };
    let real = usize::try_from(real).ok()?;
    if entries == 0 || entries > MAX_STAND_IN_ENTRIES {
        log(&format!(
            "no stand-in for {interface}: {entries} counted entries (at most {MAX_STAND_IN_ENTRIES})"
        ));
        return None;
    }
    let _creating = CREATING
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner());
    for (number, slot) in OBJECTS.iter().enumerate() {
        match slot.get() {
            Some(info) if info.real == real => return Some((info.stand_in, number)),
            Some(_) => continue,
            None => {
                let stand_in = Box::leak(Box::new(StandIn {
                    table: METHOD_TABLES[number].as_ptr() as usize,
                })) as *const StandIn as usize;
                let _ = slot.set(Object {
                    stand_in,
                    real,
                    real_table: first,
                    counted: entries,
                    name: interface.into(),
                });
                return Some((stand_in, number));
            }
        }
    }
    log(&format!(
        "no stand-in for {interface}: all {STAND_INS} are in use"
    ));
    None
}

/// Finds the call that returns now: the one whose stub entry had stack
/// pointer `entry_rsp`. Entries for deeper frames left behind (a call that
/// never returned normally) are dropped first.
fn take_pending(pending: &mut Vec<Pending>, entry_rsp: usize) -> Option<Pending> {
    while pending
        .last()
        .is_some_and(|call| call.entry_rsp < entry_rsp)
    {
        pending.pop();
    }
    if pending
        .last()
        .is_some_and(|call| call.entry_rsp == entry_rsp)
    {
        pending.pop()
    } else {
        None
    }
}

fn should_log(call: u64) -> bool {
    call <= LOG_FIRST || call.is_multiple_of(LOG_EVERY)
}

fn elapsed_ms() -> u128 {
    START.get_or_init(Instant::now).elapsed().as_millis()
}

/// The argument registers of a shadowed account-data call (ADR 0055):
/// `rcx`, `rdx` and `r8` as raw values (addresses), `r9` hidden (for
/// `FileRead` it is the size `GetFileSize` answered) and no register text
/// (the file name at `rdx`, old buffer contents at `r8`).
fn describe_registers_hidden(saved: &Saved) -> String {
    let mut line = format!(
        "rcx=0x{:x} rdx=0x{:x} r8=0x{:x} r9 hidden (account data)",
        saved.rcx, saved.rdx, saved.r8
    );
    for (number, xmm) in saved.xmm.iter().enumerate() {
        let _ = write!(line, " xmm{number}=0x{:x}", xmm[0]);
    }
    line
}

/// The argument registers as raw values, plus (with `texts`) text where an
/// integer register points to printable ASCII.
fn describe_registers(saved: &Saved, texts: bool) -> String {
    let mut line = format!(
        "rcx=0x{:x} rdx=0x{:x} r8=0x{:x} r9=0x{:x}",
        saved.rcx, saved.rdx, saved.r8, saved.r9
    );
    for (number, xmm) in saved.xmm.iter().enumerate() {
        let _ = write!(line, " xmm{number}=0x{:x}", xmm[0]);
    }
    if !texts {
        line.push_str(" (texts hidden: account data)");
        return line;
    }
    for (name, value) in [
        ("rcx", saved.rcx),
        ("rdx", saved.rdx),
        ("r8", saved.r8),
        ("r9", saved.r9),
    ] {
        if let Some(text) = ascii_at(value) {
            let _ = write!(line, " {name}->\"{text}\"");
        }
    }
    line
}

/// The printable ASCII text at `address`, if the memory there is readable
/// and holds 2 to [`MAX_TEXT`] printable characters followed by a NUL,
/// all within one memory region.
fn ascii_at(address: u64) -> Option<String> {
    // The lowest 64 KiB are never mapped on Windows; this also skips small
    // numbers that are not pointers.
    if address < 0x1_0000 {
        return None;
    }
    let start = usize::try_from(address).ok()?;
    let end = readable_end(start)?;
    let mut text = String::new();
    for offset in 0..=MAX_TEXT {
        let at = start.checked_add(offset)?;
        if at >= end {
            return None;
        }
        // SAFETY: `at` lies inside a committed, readable region that
        // `readable_end` just checked.
        let byte = unsafe { std::ptr::read_volatile(at as *const u8) };
        match byte {
            0 if text.len() >= 2 => return Some(text),
            0x20..=0x7e => text.push(char::from(byte)),
            _ => return None,
        }
    }
    None
}

/// Steps 4b and 4d (ADR 0042, 0050): if the lowest byte of `rax` is 1,
/// the first [`CALLBACK_HEADER`] bytes at `rdx` and the first
/// [`READ_BYTES`] at `r8`, as hex in groups of four bytes (memory order),
/// followed by the payload note of [`describe_payload`]. `None` for any
/// other result.
fn describe_callback(rax: u64, [rdx, r8]: [u64; 2]) -> Option<String> {
    if rax & 0xff != 1 {
        return None;
    }
    let header = bytes_in(rdx, CALLBACK_HEADER);
    let mut note = String::from("wrote rdx->");
    // Without 24 readable bytes, the 16 of step 4b as before.
    note.push_str(&header.as_deref().map_or_else(|| hex_at(rdx), hex));
    let _ = write!(note, " r8->{}", hex_at(r8));
    if let Some(header) = header {
        let _ = write!(note, " {}", describe_payload(&header, PAYLOAD_LISTED));
    }
    Some(note)
}

/// Step 4d of ADR 0050: what a callback header points to. If bytes 8 to
/// 16 hold an address and bytes 16 to 20 a size of 1 to [`MAX_PAYLOAD`]
/// that make a readable range, the size and the SHA-256 of that range;
/// for a number (bytes 4 to 8) in `listed`, also its first
/// [`PAYLOAD_SHOWN`] bytes as hex. `header` has [`CALLBACK_HEADER`] bytes.
fn describe_payload(header: &[u8], listed: &[u32]) -> String {
    let word = |at: usize| {
        u32::from_le_bytes([header[at], header[at + 1], header[at + 2], header[at + 3]])
    };
    let number = word(4);
    let address = u64::from(word(8)) | (u64::from(word(12)) << 32);
    let size = word(16) as usize;
    if size == 0 || size > MAX_PAYLOAD {
        return format!("payload: no size (bytes 16..20 = {size})");
    }
    let Some(payload) = bytes_in(address, size) else {
        return format!("payload: size {size} not readable at the address");
    };
    let mut note = format!("payload: size {size} sha256 {}", sha256_hex(&payload));
    if listed.contains(&number) {
        let shown = &payload[..size.min(PAYLOAD_SHOWN)];
        let _ = write!(note, " first {}", hex(shown));
    }
    note
}

/// The SHA-256 of `bytes` as lowercase hex.
fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    Sha256::digest(bytes)
        .iter()
        .fold(String::new(), |mut text, byte| {
            let _ = write!(text, "{byte:02x}");
            text
        })
}

/// `bytes` as hex in groups of four bytes (memory order), in brackets.
fn hex(bytes: &[u8]) -> String {
    let mut text = String::from("[");
    for (index, byte) in bytes.iter().enumerate() {
        if index > 0 && index % 4 == 0 {
            text.push(' ');
        }
        let _ = write!(text, "{byte:02x}");
    }
    text.push(']');
    text
}

/// The first [`READ_BYTES`] at `address` as hex in groups of four bytes
/// (memory order), or "not readable".
fn hex_at(address: u64) -> String {
    bytes_at(address).map_or_else(|| "not readable".to_owned(), |bytes| hex(&bytes))
}

/// Step 4c of ADR 0043: the read for a call at `slot` of the object asked
/// for with `interface`, if [`READS`] lists it. Output addresses are taken
/// from `saved` as the call started; stack arguments from above
/// `entry_rsp`, the stack pointer at the stub's entry, also as the call
/// started (only the low 32 bits and a yes or no are kept).
fn after_for(interface: &str, slot: usize, saved: &Saved, entry_rsp: usize) -> Option<After> {
    let &(_, _, read) = READS
        .iter()
        .find(|&&(name, position, _)| name == interface && position == slot)?;
    let register_value = |register: &str| match register {
        "rdx" => Some(saved.rdx),
        "r8" => Some(saved.r8),
        "r9" => Some(saved.r9),
        _ => None,
    };
    match read {
        Read::ResultText => Some(After::ResultText),
        Read::OutputBytes(register) => Some(After::Bytes {
            register,
            address: register_value(register)?,
        }),
        Read::Executable(register) => Some(After::Executable {
            register,
            address: register_value(register)?,
        }),
        Read::StackAppIdAndText => {
            let slot = |offset: usize| entry_rsp.checked_add(offset).and_then(read_u64);
            Some(After::StackAppIdAndText {
                // The page's `AppId_t` is 32 bits; the upper half is not
                // kept.
                sixth: slot(SIXTH_ARGUMENT).map(|value| value as u32),
                // `ascii_at` checks the region with VirtualQuery and stops
                // at its end; only whether a text is there is kept.
                seventh_is_text: slot(SEVENTH_ARGUMENT).map(|value| ascii_at(value).is_some()),
            })
        }
    }
}

/// The call's shadow-mode entry, if [`SHADOWS`] lists it (ADR 0046).
fn shadow_for(interface: &str, slot: usize) -> Option<Shadow> {
    SHADOWS
        .iter()
        .find(|&&(name, position, _)| name == interface && position == slot)
        .map(|&(_, _, shadow)| shadow)
}

/// Compares the official client's result `rax` with Reborn's answer
/// (ADR 0046). Only the values shadow mode compares are shown; none of them
/// is account data.
fn describe_shadow(rax: u64, shadow: Shadow, app_id: Option<u32>) -> String {
    match shadow {
        Shadow::AppId => {
            let Some(reborn) = app_id else {
                return "shadow: no app ID given".to_owned();
            };
            // The documented result is a 32-bit number; the upper half of
            // rax is not part of it.
            let client = rax as u32;
            let verdict = if client == reborn {
                "match"
            } else {
                "mismatch"
            };
            format!("shadow {verdict}: client {client}, Reborn {reborn}")
        }
        Shadow::BatteryPower => {
            let client = rax as u8;
            let reborn = battery_power();
            let verdict = if client == reborn {
                "match"
            } else {
                "mismatch"
            };
            format!("shadow {verdict}: client {client}, Reborn {reborn}")
        }
        // Needs `rebornd`'s answer: compared by the worker thread
        // (`ask`), never here.
        Shadow::Subscribed
        | Shadow::PersonaName
        | Shadow::FileSize
        | Shadow::FileRead
        | Shadow::AchievementCount
        | Shadow::AchievementName => "shadow: asked rebornd".to_owned(),
    }
}

/// 255 on AC power or when unknown, otherwise the battery percent, from
/// `GetSystemPowerStatus` as Microsoft documents it (`ACLineStatus` 1 is AC
/// power; `BatteryLifePercent` 255 is unknown).
fn battery_power() -> u8 {
    use windows_sys::Win32::System::Power::{GetSystemPowerStatus, SYSTEM_POWER_STATUS};
    // SAFETY: an all-zero SYSTEM_POWER_STATUS is valid; the call fills it.
    let mut status: SYSTEM_POWER_STATUS = unsafe { std::mem::zeroed() };
    // SAFETY: `status` is a valid, writable SYSTEM_POWER_STATUS.
    if unsafe { GetSystemPowerStatus(&mut status) } == 0 {
        return 255;
    }
    if status.ACLineStatus == 1 || status.BatteryLifePercent > 100 {
        255
    } else {
        status.BatteryLifePercent
    }
}

/// The log note for a listed call that returned with `rax` (step 4c).
/// Nothing beyond the text or the [`READ_BYTES`] is read.
fn describe_after(rax: u64, after: After) -> String {
    match after {
        After::ResultText => match ascii_at(rax) {
            Some(text) => format!("result->\"{text}\""),
            None => "result: no text".to_owned(),
        },
        After::Bytes { register, address } => {
            format!("after {register}->{}", hex_at(address))
        }
        After::Executable { register, address } => {
            let executable = usize::try_from(address).is_ok_and(is_executable);
            let verdict = if executable {
                "executable"
            } else {
                "not executable"
            };
            let place = executable_place(address, executable, MODULE.get().copied());
            format!("after {register}: {verdict}{place}")
        }
        After::StackAppIdAndText {
            sixth,
            seventh_is_text,
        } => {
            let sixth = sixth.map_or_else(|| "not readable".to_owned(), |value| value.to_string());
            let seventh = match seventh_is_text {
                Some(true) => "yes",
                Some(false) => "no",
                None => "not readable",
            };
            format!("stack: slot 6 low 32 bits {sixth}, slot 7 text {seventh}")
        }
    }
}

/// Where an executable address lies: in `steamclient64` (`module`, its
/// start and end) or outside it; nothing for memory that is not
/// executable or when the module's range is not known.
fn executable_place(
    address: u64,
    executable: bool,
    module: Option<(usize, usize)>,
) -> &'static str {
    match module {
        Some((base, end)) if executable => {
            if usize::try_from(address).is_ok_and(|at| (base..end).contains(&at)) {
                " (in steamclient64)"
            } else {
                " (outside steamclient64)"
            }
        }
        _ => "",
    }
}

/// The first [`READ_BYTES`] at `address`, if they all lie in one
/// committed, readable memory region.
fn bytes_at(address: u64) -> Option<[u8; READ_BYTES]> {
    // As in `ascii_at`: the lowest 64 KiB are never mapped.
    if address < 0x1_0000 {
        return None;
    }
    let start = usize::try_from(address).ok()?;
    let end = readable_end(start)?;
    if start.checked_add(READ_BYTES)? > end {
        return None;
    }
    // SAFETY: the bytes lie inside a committed, readable region that
    // `readable_end` just checked; no alignment is assumed.
    Some(unsafe { std::ptr::read_unaligned(start as *const [u8; READ_BYTES]) })
}

/// The `len` bytes at `address`, if they all lie in one committed,
/// readable memory region (as [`bytes_at`]).
fn bytes_in(address: u64, len: usize) -> Option<Vec<u8>> {
    // As in `ascii_at`: the lowest 64 KiB are never mapped.
    if address < 0x1_0000 {
        return None;
    }
    let start = usize::try_from(address).ok()?;
    let end = readable_end(start)?;
    if start.checked_add(len)? > end {
        return None;
    }
    let mut bytes = Vec::with_capacity(len);
    // SAFETY: the `len` bytes lie inside a committed, readable region that
    // `readable_end` just checked, and `bytes` has room for `len` bytes; no
    // reference to the game's memory is made, so other threads writing it
    // is no aliasing violation. As in `bytes_at`, the memory is assumed not
    // to be freed between the check and the copy.
    unsafe {
        std::ptr::copy_nonoverlapping(start as *const u8, bytes.as_mut_ptr(), len);
        bytes.set_len(len);
    }
    Some(bytes)
}

/// Windows' information about the memory at `address`, if it is
/// committed and not a guard page.
fn region(address: usize) -> Option<MEMORY_BASIC_INFORMATION> {
    // SAFETY: MEMORY_BASIC_INFORMATION is plain data; all zeros is valid.
    let mut info: MEMORY_BASIC_INFORMATION = unsafe { std::mem::zeroed() };
    let size = size_of::<MEMORY_BASIC_INFORMATION>();
    // SAFETY: VirtualQuery only inspects the address space; `info` is
    // writable for `size` bytes.
    let written = unsafe { VirtualQuery(address as *const _, &mut info, size) };
    if written == 0 || info.State != MEM_COMMIT || info.Protect & PAGE_GUARD != 0 {
        return None;
    }
    Some(info)
}

/// The end of the committed, readable memory region containing `address`.
fn readable_end(address: usize) -> Option<usize> {
    let info = region(address)?;
    let readable = PAGE_READONLY
        | PAGE_READWRITE
        | PAGE_WRITECOPY
        | PAGE_EXECUTE_READ
        | PAGE_EXECUTE_READWRITE
        | PAGE_EXECUTE_WRITECOPY;
    if info.Protect & readable == 0 {
        return None;
    }
    (info.BaseAddress as usize).checked_add(info.RegionSize)
}

/// Whether Windows marks the memory at `address` as executable. Only the
/// protection is asked for; the memory itself is not read.
fn is_executable(address: usize) -> bool {
    let executable =
        PAGE_EXECUTE | PAGE_EXECUTE_READ | PAGE_EXECUTE_READWRITE | PAGE_EXECUTE_WRITECOPY;
    region(address).is_some_and(|info| info.Protect & executable != 0)
}

/// Eight bytes at `address`, if they lie in readable memory.
fn read_u64(address: usize) -> Option<u64> {
    let end = readable_end(address)?;
    if address.checked_add(8)? > end {
        return None;
    }
    // SAFETY: the eight bytes lie inside a committed, readable region that
    // `readable_end` just checked; no alignment is assumed.
    Some(unsafe { std::ptr::read_unaligned(address as *const u64) })
}

/// Step 3a of ADR 0040: whether the first field of `object` holds an
/// address inside the module `[base, end)`, and if so, how many
/// consecutive eight-byte values from there are addresses inside the
/// module that Windows marks as executable. Only pointer values in data
/// are read, never code bytes.
fn shape_of(object: u64, (base, end): (usize, usize)) -> Shape {
    let Ok(object) = usize::try_from(object) else {
        return Shape::NotAnAddress;
    };
    if object < 0x1_0000 {
        return Shape::NotAnAddress;
    }
    let Some(first) = read_u64(object).and_then(|value| usize::try_from(value).ok()) else {
        return Shape::Unreadable;
    };
    if !(base..end).contains(&first) {
        return Shape::Elsewhere;
    }
    let mut entries = 0;
    while entries < MAX_TABLE {
        let Some(entry) = first
            .checked_add(entries * 8)
            .and_then(read_u64)
            .and_then(|value| usize::try_from(value).ok())
        else {
            break;
        };
        if !(base..end).contains(&entry) || !is_executable(entry) {
            break;
        }
        entries += 1;
    }
    Shape::Table { first, entries }
}

/// What step 3a found at an object.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Shape {
    NotAnAddress,
    Unreadable,
    /// The first field does not point into the module.
    Elsewhere,
    /// The first field points to `first` in the module, followed by
    /// `entries` addresses in its executable memory.
    Table {
        first: usize,
        entries: usize,
    },
}

fn describe_shape(shape: &Shape, (base, _): (usize, usize)) -> String {
    match *shape {
        Shape::NotAnAddress => "shape: not an address".to_owned(),
        Shape::Unreadable => "shape: object not readable".to_owned(),
        Shape::Elsewhere => "shape: first field does not point into steamclient64".to_owned(),
        Shape::Table { first, entries } => format!(
            "shape: first field -> steamclient64+0x{:x}, {entries} entries point into its executable memory{}",
            first - base,
            if entries == MAX_TABLE {
                " (limit reached)"
            } else {
                ""
            }
        ),
    }
}

/// Start and end of a loaded module (Microsoft's GetModuleInformation).
fn module_range(module: HMODULE) -> Option<(usize, usize)> {
    // SAFETY: MODULEINFO is plain data; all zeros is valid.
    let mut info: MODULEINFO = unsafe { std::mem::zeroed() };
    let size = u32::try_from(size_of::<MODULEINFO>()).ok()?;
    // SAFETY: `module` is a module loaded in this process; `info` is
    // writable for `size` bytes; GetCurrentProcess returns a pseudo handle
    // that needs no closing.
    let found = unsafe { K32GetModuleInformation(GetCurrentProcess(), module, &mut info, size) };
    if found == 0 {
        return None;
    }
    let base = info.lpBaseOfDll as usize;
    Some((base, base.checked_add(info.SizeOfImage as usize)?))
}

fn log(line: &str) {
    if let Some(file) = LOG.get_or_init(open_log) {
        let mut file = file.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
        let _ = writeln!(file, "{line}");
    }
}

fn open_log() -> Option<Mutex<File>> {
    let path = own_dir()?.join(format!("observe-{}.log", std::process::id()));
    File::create(path).ok().map(Mutex::new)
}

fn targets() -> &'static [usize; 5] {
    TARGETS.get_or_init(|| match load_real() {
        Ok(targets) => targets,
        Err(reason) => {
            log(&format!("cannot forward: {reason}"));
            std::process::abort()
        }
    })
}

/// Loads the real `steamclient64.dll` from the saved path and looks up the
/// five entry points in it.
fn load_real() -> Result<[usize; 5], String> {
    let dir = own_dir().ok_or("cannot find the proxy's own folder")?;
    let original = std::fs::read_to_string(dir.join(SAVED))
        .map_err(|error| format!("cannot read the saved path: {error}"))?;
    log(&format!("loading the real DLL from {original}"));
    if !std::path::Path::new(&original).is_absolute() {
        return Err(format!("the saved path is not absolute: {original}"));
    }
    let wide: Vec<u16> = original.encode_utf16().chain(Some(0)).collect();
    // The real DLL needs DLLs from its own folder (`tier0_s64.dll` and
    // `vstdlib_s64.dll` load from the official client's folder right after
    // it, `docs/shim/loading.md`); a plain LoadLibraryW looked in the
    // game's folder and failed with error 126 (live, 2026-11-21). With an
    // absolute path, LOAD_WITH_ALTERED_SEARCH_PATH makes Windows search the
    // loaded DLL's folder first (Microsoft's LoadLibraryExW documentation).
    // SAFETY: `wide` is a NUL-terminated UTF-16 absolute path that lives for
    // the call; the file handle argument must be null.
    let module = unsafe {
        LoadLibraryExW(
            wide.as_ptr(),
            std::ptr::null_mut(),
            LOAD_WITH_ALTERED_SEARCH_PATH,
        )
    };
    if module.is_null() {
        return Err(format!(
            "LoadLibraryExW failed: {}",
            std::io::Error::last_os_error()
        ));
    }
    match module_range(module) {
        Some(range) => {
            let _ = MODULE.set(range);
        }
        None => log("cannot find the real DLL's memory range; shapes are not logged"),
    }
    let mut targets = [0usize; 5];
    for (slot, name) in targets.iter_mut().zip(ENTRY_POINTS) {
        let mut ascii = name.as_bytes().to_vec();
        ascii.push(0);
        // SAFETY: `module` is a loaded module that is never freed; `ascii`
        // is a NUL-terminated ASCII name that lives for the call.
        let address = unsafe { GetProcAddress(module, ascii.as_ptr()) };
        *slot = address
            .map(|function| function as usize)
            .ok_or_else(|| format!("the real DLL has no {name}"))?;
    }
    Ok(targets)
}

/// The folder this DLL was loaded from.
fn own_dir() -> Option<PathBuf> {
    let mut module: HMODULE = std::ptr::null_mut();
    // SAFETY: with FROM_ADDRESS the "name" is an address inside this module
    // (this function); UNCHANGED_REFCOUNT takes no reference that would
    // need releasing. `module` is a valid place for the handle.
    let found = unsafe {
        GetModuleHandleExW(
            GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT,
            own_dir as *const () as *const u16,
            &mut module,
        )
    };
    if found == 0 {
        return None;
    }
    let mut buffer = vec![0u16; 32_768];
    let capacity = u32::try_from(buffer.len()).unwrap_or(u32::MAX);
    // SAFETY: `module` is this module's handle; `buffer` is writable for
    // `capacity` UTF-16 units.
    let length = unsafe { GetModuleFileNameW(module, buffer.as_mut_ptr(), capacity) };
    if length == 0 || length >= capacity {
        return None;
    }
    let path = PathBuf::from(String::from_utf16_lossy(&buffer[..length as usize]));
    path.parent().map(PathBuf::from)
}

