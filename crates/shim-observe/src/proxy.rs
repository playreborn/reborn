//! The observation proxy (ADR 0038 stage 2, ADR 0039): it forwards the five
//! entry points a game asks `steamclient64.dll` for
//! (`docs/shim/entry-points.md`) to the real DLL and logs each call's raw
//! argument registers and its raw result.
//!
//! Nothing is known about the entry points' arguments, so each one is a
//! small assembly stub (Microsoft x64 calling convention, as documented by
//! Microsoft):
//!
//! 1. It saves the four integer and four floating-point argument registers
//!    and hands a copy, the game's return address and the stack position
//!    to `observe_call`, which logs the call, remembers the return address
//!    in a per-thread stack and returns the real function's address.
//! 2. It replaces the return address on the stack with the return stub,
//!    puts the registers back, restores the stack pointer and jumps to the
//!    real function, which so sees the game's exact arguments.
//! 3. When the real function returns, it lands in the return stub, which
//!    hands `rax` and `xmm0` (the result registers) to `observe_return`,
//!    gets the game's return address back and jumps there with the result
//!    untouched.
//!
//! Logged per call: the raw register values; for an integer register that
//! points to readable memory holding 2 to 64 printable ASCII characters
//! and a NUL, that text. Memory is checked with `VirtualQuery` before it is
//! read. Nothing else is read (apart from steps 4b and 4c below), so binary data
//! such as tickets never ends up in the log.
//!
//! The real DLL is loaded on the first call, not while this DLL is being
//! loaded (Windows forbids loading libraries from `DllMain`). Its path is
//! the value `reborn-observe arm` saved next to this DLL.
//!
//! Step 3b of ADR 0040: when `CreateInterface` returns an object whose
//! first field points to a table of addresses in the real DLL's executable
//! memory (step 3a), the game gets a stand-in object instead. Its first
//! field points to a table of stubs generated by `build.rs`, one per stand-in
//! and position. Each stub hands its number to `observe_method`, which puts
//! the real object's address into `rcx` only if `rcx` holds the stand-in
//! (and logs either way), logs the call, and returns the entry at the same
//! position of the real object's table. The real table is only read.
//! Nothing of Valve's is changed. A file `read-only` next to this DLL
//! (`reborn-observe arm --read-only`) turns stand-ins off.
//!
//! Step 3c (ADR 0041): a call through a stand-in that passed a text and
//! returns an object of the step 3a shape gets a stand-in for that result
//! too, named after the text. Any argument register that holds a
//! stand-in's address gets the real object before the real code runs.
//!
//! Step 4b (ADR 0042): after a `Steam_BGetCallback` call whose result's
//! lowest byte is 1, the first 16 bytes at the addresses `rdx` and `r8`
//! held when the call started are logged as hex, each only if
//! `VirtualQuery` shows them readable. Nothing beyond them is read.

//!
//! Step 4c (ADR 0043): for calls through stand-ins listed in `READS`,
//! and only when the call is logged, the proxy also logs after the return
//! either the text `rax` points to (same rules as argument texts) or the
//! first 16 bytes at the address one argument register held when the call
//! started. Calls not on the list are logged as before.
//!
//! Step 4d (ADR 0050): at `rdx` the proxy reads 24 bytes instead of 16.
//! If bytes 8 to 16 hold an address and bytes 16 to 20 a size of at most
//! 4096 that make a readable range, it logs that size and the SHA-256 of
//! the range, never its content. Only for callback numbers (bytes 4 to 8)
//! listed in `PAYLOAD_LISTED` it also logs the first 64 bytes as hex.
//!
//! Shadow mode (ADR 0046): for confirmed meanings listed in `SHADOWS`,
//! and only when the call is logged, the proxy compares the official
//! client's result with Reborn's own answer and logs match or mismatch.
//! The game always gets the official client's result.
//!
//! Answer mode (ADR 0046): for calls in `ANSWERS` (shadow mode matched in
//! three games, maintainer's OK) and an app ID given by `reborn-observe arm
//! --app`, the stub jumps to Reborn's own function instead of the official
//! client's; the result still goes through the return stub and is logged.
