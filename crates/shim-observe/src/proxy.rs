/// Reborn's own answer to a confirmed meaning (shadow mode, ADR 0046).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Shadow {
    /// `GetAppID`: the app ID `reborn-observe arm --app` gave the proxy,
    /// compared with the low 32 bits of the result.
    AppId,
    /// `GetCurrentBatteryPower`: 255 on AC power, else the battery percent
    /// from `GetSystemPowerStatus`, compared with the lowest byte.
    BatteryPower,
    /// `BIsSubscribed`: whether `rebornd` says the account owns the app
    /// given by `reborn-observe arm --app` (ADR 0055: account data comes
    /// from `rebornd`, not from `arm`), compared with the lowest byte.
    /// Asked on a worker thread, so the game's call is not delayed; only
    /// match or mismatch is logged.
    Subscribed,
    /// `SteamFriends017` position 0, `GetPersonaName` (experiment 33,
    /// under A1, `docs/shim/meanings.md`): whether the text the result
    /// points to is the account's persona name, as `rebornd` says from the
    /// SHA-256 the proxy sends (ADR 0056). The text is account data: never logged, and the call line
    /// shows no register texts.
    PersonaName,
    /// `GetFileSize(name)`: the size `rebornd` reads for the name in its
    /// shadow folder (ADR 0055, stage 1), compared with the low 32 bits of
    /// the result. Asked like [`Shadow::Subscribed`].
    FileSize,
    /// `FileRead(name, buffer, size)`: the bytes `rebornd` reads for the
    /// name in its shadow folder (at most `size`), compared by count and
    /// SHA-1 with what the official client wrote into the game's buffer.
    /// Asked like [`Shadow::Subscribed`].
    FileRead,
    /// `GetNumAchievements` (ADR 0059, decision 2): the low 32 bits of the
    /// result, compared with the length of Reborn's achievement list once
    /// `rebornd`'s `StatsReceived` is there.
    AchievementCount,
    /// `GetAchievementName(index)` (ADR 0059, decision 2): the SHA-256 of
    /// the text the result points to, compared with Reborn's name at the
    /// same index once the list is there. The text is never logged.
    AchievementName,
}

impl Shadow {
    /// Whether the call's arguments and result are account data, compared
    /// through `rebornd` and kept out of the log (ADR 0055: "The log says
    /// only `shadow match` or `shadow mismatch`").
    fn is_account_data(self) -> bool {
        matches!(
            self,
            Shadow::Subscribed | Shadow::FileSize | Shadow::FileRead
        )
    }

    /// Whether the call passes a cloud file name in `rdx`.
    fn takes_file_name(self) -> bool {
        matches!(self, Shadow::FileSize | Shadow::FileRead)
    }

    /// Whether the call is one of the achievement comparisons.
    fn is_achievement(self) -> bool {
        matches!(self, Shadow::AchievementCount | Shadow::AchievementName)
    }
}

