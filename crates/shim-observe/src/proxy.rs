    #[test]
    fn stand_ins_forward_to_the_real_object() {
        let _ = LOG.set(None);
        let _ = READ_ONLY.set(false);
        let module = own_module();
        let _ = MODULE.set(module);
        static REAL_TABLE: OnceLock<[usize; 3]> = OnceLock::new();
        let table = REAL_TABLE.get_or_init(|| {
            [
                method_this as *const () as usize,
                method_float as *const () as usize,
                0,
            ]
        });
        // The real object: its table, then a field the methods read.
        let real = Box::leak(Box::new([table.as_ptr() as usize, 40usize]));
        let real_address = real.as_ptr() as usize;
        let shape = shape_of(real_address as u64, module);
        let (stand_in, number) =
            stand_in_for(real_address as u64, &shape, "Fake001").expect("a stand-in");
        assert_ne!(stand_in, real_address);
        // Asking again for the same real object gives the same stand-in.
        assert_eq!(
            stand_in_for(real_address as u64, &shape, "Fake001"),
            Some((stand_in, number))
        );
        // Call like a game would: through the stand-in's table, with the
        // stand-in as the first argument.
        // SAFETY: the stand-in's first field points to its stub table; the
        // stubs forward to the methods above, which have these signatures.
        unsafe {
            let stubs = *(stand_in as *const usize) as *const usize;
            let first: extern "C" fn(*const usize, u64) -> u64 = std::mem::transmute(*stubs);
            let second: extern "C" fn(*const usize, f64) -> f64 =
                std::mem::transmute(*stubs.add(1));
            // The real method gets the real object.
            assert_eq!(first(stand_in as *const usize, 5), real_address as u64 + 5);
            assert_eq!(second(stand_in as *const usize, 2.5), 42.5);
            // Something else in rcx is passed on unchanged.
            assert_eq!(first(std::ptr::null(), 7), 7);
        }
        PENDING.with(|pending| assert!(pending.borrow().is_empty(), "every call returned"));
        assert_eq!(METHOD_CALLS[number * SLOTS].load(Ordering::Relaxed), 2);
        // Shapes that do not fit get no stand-in.
        assert_eq!(stand_in_for(0x10, &Shape::NotAnAddress, "x"), None);
        let too_big = Shape::Table {
            first: table.as_ptr() as usize,
            entries: MAX_STAND_IN_ENTRIES + 1,
        };
        assert_eq!(stand_in_for(real_address as u64 + 8, &too_big, "x"), None);
    }

    // A made-up parent object whose methods hand out a child object (when
