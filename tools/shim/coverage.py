"""Regenerates the tables of docs/shim/coverage.md and docs/shim/gaps.md.

Reads the reference runs listed in games.json from the local proxy logs
and the statuses in status.json. Run from the repository root:

    python tools/shim/coverage.py

The logs stay on the recorder's computer; only interface version texts,
position numbers and counts go into the docs.

games.json has the 20 games of the M4 list (`games`) and recordings of
other games (`extra`, ADR 0056 decision 3). Both count in the tables and
the gap list; the totals are also printed for the M4 games alone, for the
percentages of PROGRESS.md.
"""
import collections
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import observelog  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).parent


def load():
    data = json.loads((HERE / "games.json").read_text(encoding="utf-8"))
    m4 = [g + [True] for g in data["games"]]
    extra = [g + [False] for g in data.get("extra", [])]
    status = json.loads((HERE / "status.json").read_text(encoding="utf-8"))
    status.pop("_comment", None)
    return m4 + extra, status


def collect(games):
    use = collections.defaultdict(lambda: collections.defaultdict(set))
    interface_positions = collections.defaultdict(set)
    clients = {}
    for code, _name, _app, log, _who, _m4 in games:
        path = observelog.log_dir() / log
        for c in observelog.calls(path):
            use[c.interface][code].add(c.position)
            if "r9" in c.texts or (c.position == 9 and c.interface.startswith("SteamClient")):
                interface_positions[c.interface].add(c.position)
        clients[code] = observelog.first_steam_client(path)
    return use, interface_positions, clients


def status_of(status, interface, position, interface_positions):
    entry = status.get(interface, {})
    if str(position) in entry:
        return entry[str(position)]
    if position in interface_positions.get(interface, ()) and "*interface" in entry:
        return entry["*interface"]
    return ["not known", ""]


def sort_key(interface):
    return (re.sub(r"\d+$", "", interface).lower(), interface)


def tables(games, status):
    use, interface_positions, clients = collect(games)
    order = [g[0] for g in games]
    game_rows = ["| Game | Code | `SteamClient` | Recorded by | M4 list |", "| --- | --- | --- | --- | --- |"]
    for code, name, app, _log, who, m4 in games:
        game_rows.append(f"| {name} ({app}) | {code} | `{clients[code]}` | {who} | {'yes' if m4 else 'no'} |")
    m4_codes = {g[0] for g in games if g[5]}
    pos_rows = ["| Interface version | Games | Positions called | Status |", "| --- | --- | --- | --- |"]
    gaps = []
    for interface in sorted(use, key=sort_key):
        by = use[interface]
        groups = collections.OrderedDict()
        for code in order:
            if code in by:
                groups.setdefault(" ".join(map(str, sorted(by[code]))), []).append(code)
        positions = "; ".join(f"{p} ({', '.join(c)})" for p, c in groups.items()) if len(groups) > 1 else next(iter(groups))
        known = collections.OrderedDict()
        all_positions = sorted(set().union(*by.values()))
        for p in all_positions:
            st, meaning = status_of(status, interface, p, interface_positions)
            games_calling = sum(1 for code in by if p in by[code])
            in_m4 = any(p in by[code] for code in by if code in m4_codes)
            if st in ("confirmed", "candidate"):
                known.setdefault(st, []).append(f"{p} {meaning}".strip())
            gaps.append((st, games_calling, interface, p, meaning, in_m4))
        cell = "; ".join(f"{st}: " + ", ".join(items) for st, items in known.items()) or "not known"
        pos_rows.append(f"| `{interface}` | {len(by)} | {positions} | {cell} |")
    return "\n".join(game_rows), "\n".join(pos_rows), gaps


def write_coverage(game_table, pos_table):
    path = ROOT / "docs" / "shim" / "coverage.md"
    text = path.read_text(encoding="utf-8")
    a = text.index("## Games\n\n") + len("## Games\n\n")
    b = text.index("\n\n## Positions")
    text = text[:a] + game_table + text[b:]
    marker = "Positions are listed in the order of their numbers.\n\n"
    a = text.index(marker) + len(marker)
    b = text.index("\n\nBeyond these")
    text = text[:a] + pos_table + text[b:]
    path.write_text(text, encoding="utf-8", newline="\n")


def write_gaps(gaps, game_count, m4_count):
    rank = {"not known": 0, "candidate": 1, "objects": 2, "confirmed": 3}
    open_gaps = sorted((g for g in gaps if g[0] != "confirmed"), key=lambda g: (rank[g[0]], -g[1], g[2], g[3]))
    done = sum(1 for g in gaps if g[0] == "confirmed")
    m4 = [g for g in gaps if g[5]]
    m4_done = sum(1 for g in m4 if g[0] == "confirmed")
    lines = [
        "# Gaps",
        "",
        "Generated by `tools/shim/coverage.py` from the recordings of",
        f"`coverage.md` ({game_count} games, {m4_count} of them on the M4 list) and",
        "`tools/shim/status.json`. Do not edit by hand. The loop (`LOOP.md`,",
        "ADR 0051) takes the first row: unknown positions before candidates,",
        "most-called first.",
        "",
        f"Positions recorded: {len(gaps)}; confirmed: {done}; open: {len(open_gaps)}.",
        f"Of these, called by the M4 games: {len(m4)}; confirmed: {m4_done}; open: {len(m4) - m4_done}.",
        "",
        "| Status | Games | Interface version | Position | Candidate |",
        "| --- | --- | --- | --- | --- |",
    ]
    for st, n, interface, p, meaning, _in_m4 in open_gaps:
        lines.append(f"| {st} | {n} | `{interface}` | {p} | {meaning} |")
    (ROOT / "docs" / "shim" / "gaps.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return len(gaps), done, len(open_gaps), len(m4), m4_done


def main():
    games, status = load()
    game_table, pos_table, gaps = tables(games, status)
    write_coverage(game_table, pos_table)
    m4_count = sum(1 for g in games if g[5])
    total, done, open_count, m4_total, m4_done = write_gaps(gaps, len(games), m4_count)
    print(f"coverage.md and gaps.md written: {total} positions, {done} confirmed, {open_count} open; "
          f"M4 games alone: {m4_total} positions, {m4_done} confirmed")


if __name__ == "__main__":
    main()
